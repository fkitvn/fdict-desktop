const TEXT = { vi, en, fr };

function applyUiLang(id) {
  const next = IDS.includes(id) ? id : "vi";
  uiLang.value = next;
  if (typeof document !== "undefined") document.documentElement.lang = next;
}

export function loadUiLang() {
  let saved = "";
  try {
    saved = localStorage.getItem(KEY) || "";
  } catch {
    saved = "";
  }
  applyUiLang(saved);
}

export function setUiLang(id) {
  const next = IDS.includes(id) ? id : "vi";
  applyUiLang(next);
  try {
    localStorage.setItem(KEY, next);
  } catch {
    /* keep the choice for this session */
  }
}

export function t(key, vars) {
  const pack = TEXT[uiLang.value] || vi;
  let text = pack[key];
  if (text == null) text = vi[key];
  if (text == null) return key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? "" : String(vars[name])));
}

try {
  if (typeof localStorage !== "undefined") loadUiLang();
} catch {
  /* first paint stays Vietnamese */
}

if (typeof window !== "undefined") {
  window.addEventListener("storage", (event) => {
    if (event.key === KEY) loadUiLang();
  });
}
